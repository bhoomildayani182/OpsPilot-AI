"""Explicit local demonstration report. Never simulates a Bedrock response or decision."""

from src.bedrock_analyzer import validate_report
from src.models import Finding, Incident, Report, ToolResult
from src.presentation import metric_sentence


class SampleReportGenerator:
    def __init__(self):
        self.last_metadata = None

    def generate(self, incident: Incident, selected_tools: list[str], results: list[ToolResult]):
        evidence = [e for result in results for e in result.evidence]
        ids = [e.id for e in evidence[:30]]
        paragraphs = []
        for result in results:
            if result.tool == "metrics":
                for item, (name, values) in zip(
                    result.evidence, result.details.items(), strict=True
                ):
                    paragraphs.append(f"Measurements [{item.id}]: {metric_sentence(name, values)}")
            elif result.tool == "logs" and result.evidence:
                refs = ", ".join(item.id for item in result.evidence[:8])
                first = incident.logs[int(result.evidence[0].id[1:]) - 1].message
                paragraphs.append(
                    f"Application logs [{refs}]: {result.details['matching_lines']} of {result.details['total_lines']} supplied messages matched the error checks. First message: {first[:240]}"
                )
            elif result.tool == "deployments":
                for item, event in zip(result.evidence, result.details["events"], strict=True):
                    delta = event["minutes_from_onset"]
                    timing = f"{abs(delta):g} minutes {'before' if delta < 0 else 'after'} the reported incident start"
                    paragraphs.append(
                        f"Release [{item.id}]: {event['version']} was recorded as {event['status']}, {timing}. Timing alone does not establish causation."
                    )
        observations = "\n\n".join(paragraphs)
        actions = {
            "metrics": "Compare the exact measurements with the service's normal baseline and approved alert thresholds; inspect processes during the same window.",
            "logs": "Review the cited application errors and surrounding messages in the same time window; check configuration and dependency failures before proposing changes.",
            "deployments": "Compare the cited release and rollback events with the symptom's start time; ask the service owner to review the change. Timing alone does not prove causation.",
        }
        report = Report(
            incident_summary=(
                "DEMO / SAMPLE REPORT — formatted locally from this run's evidence; not generated by Amazon Bedrock.\n\n"
                f"Reported symptom: {incident.title[:1000]}\n\n"
                + (observations[:1600] if evidence else "No matching observations were collected.")
            ),
            severity="unknown",
            severity_rationale=Finding(
                statement="Service impact and severity have not been established. This sample report does not perform AI severity assessment.",
                evidence_ids=ids,
            ),
            potential_root_causes=[],
            confidence="low",
            uncertainty=[
                "This is an explicit template-based demo report, not a live Bedrock response.",
                "Observed measurements and events do not establish a root cause or actual user impact.",
                "The report uses only tools selected by the real Decider for this run; unselected data has not been analyzed.",
            ],
            recommended_steps=[actions[name] for name in selected_tools if name in actions]
            or [
                "Supply an actionable symptom with timestamped measurements, logs or release events."
            ],
            additional_information_required=[
                "Confirm affected service, user impact and the incident time window.",
                "Collect any missing application logs, relevant measurements and release details.",
                "Use Full AI investigation after AWS permits Bedrock reporting to obtain an AI-generated explanation.",
            ],
        )
        validate_report(report, results)
        self.last_metadata = {
            "provider": "Local sample report",
            "report_kind": "sample",
            "generator": "deterministic evidence formatter",
            "bedrock_called": False,
            "structured_output_validated": False,
            "sample_schema_validated": True,
            "evidence_ids_validated": True,
            "aws_responses": [],
        }
        return report


def is_sample_report(metadata: dict | None) -> bool:
    return bool(metadata and metadata.get("report_kind") == "sample")
